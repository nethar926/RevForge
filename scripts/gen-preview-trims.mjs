/**
 * Preview-trim generator: level-matches each public/snippets/<id>.wav to its LIVE engine at the
 * cruise operating point, so tapping a preview is neither louder nor quieter than starting the
 * pack (HIG: consistent loudness across playback sources).
 *
 *   live   = integrated LUFS of the shipped createEngineSynth graph at cruise
 *            (speed .5 / throttle .35 / load .3), settled 2–6 s window, seeded (scripts/live-render.mjs)
 *   file   = integrated LUFS + sample peak of the WAV
 *   exact  = live − file
 *   applied = min(exact, PEAK_CEILING_DB − peak) → a trimmed preview never peaks above the
 *            master-bus limiter knee, so the limiter stays transparent on previews.
 *
 * Writes src/audio/previewTrims.ts (generated — do not hand-edit).
 *   node scripts/gen-preview-trims.mjs          regenerate
 *   node scripts/gen-preview-trims.mjs --check  exit 1 if the committed table is stale (±0.05 dB)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { integratedLufs, readWav16, samplePeakDb } from './loudness.mjs';
import { renderLive } from './live-render.mjs';
import { createJiti } from 'jiti';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/audio/previewTrims.ts');
const PEAK_CEILING_DB = -3;
const CRUISE = () => ({ speed: 0.5, throttle: 0.35, load: 0.3 });
const DUR = 6, FROM = 2;
// Packs whose start() runs an audible start sequence get a longer settle before the cruise window
// (Tomcat: air starter → light-off → idle ≈ 3.4 s, then spool to cruise).
const SETTLE = { 'aerospace-f14': { dur: 11, from: 7 } };
// Packs that get no preview trim at all (Twin Ion: rework pending; plays at file level).
export const NO_TRIM = new Set(['ion-twin']);
const r2 = (x) => Math.round(x * 100) / 100;

const jiti = createJiti(import.meta.url, { interopDefault: true });
const { getBuiltin } = await jiti.import(join(ROOT, 'src/audio/index.ts'));
// Packs whose id lives in ONE identity constant are keyed by that constant (rename = one line).
const { CHRONO_COUPE } = await jiti.import(join(ROOT, 'src/audio/chronoCoupePack.ts'));
const keyOf = (id) => (id === CHRONO_COUPE.id ? '[CHRONO_COUPE.id]' : `'${id}'`);
const dir = join(ROOT, 'public/snippets');
const ids = readdirSync(dir).filter((f) => f.endsWith('.wav')).map((f) => f.slice(0, -4)).filter((id) => getBuiltin(id) && !NO_TRIM.has(id)).sort();

const rows = [];
for (const id of ids) {
  const win = SETTLE[id] ?? { dur: DUR, from: FROM };
  const buf = await renderLive(id, CRUISE, win.dur);
  const s = Math.round(win.from * buf.sampleRate);
  const live = integratedLufs(Array.from({ length: buf.numberOfChannels }, (_, c) => buf.getChannelData(c).subarray(s)), buf.sampleRate);
  const { fs, channels } = readWav16(readFileSync(join(dir, `${id}.wav`)));
  const file = integratedLufs(channels, fs);
  const peak = samplePeakDb(channels);
  const exact = live - file;
  const applied = Math.min(exact, PEAK_CEILING_DB - peak);
  rows.push({ id, liveCruiseLufs: r2(live), previewLufs: r2(file), previewPeakDb: r2(peak), exactDb: r2(exact), trimDb: r2(applied), clamped: applied < exact - 0.005 });
  console.log(`${id.padEnd(18)} live ${live.toFixed(2).padStart(7)}  file ${file.toFixed(2).padStart(7)}  peak ${peak.toFixed(2).padStart(6)}  exact ${exact >= 0 ? '+' : ''}${exact.toFixed(2)}  trim ${applied >= 0 ? '+' : ''}${applied.toFixed(2)}${applied < exact - 0.005 ? '  (peak-clamped)' : ''}`);
}

const body = `/**
 * GENERATED by scripts/gen-preview-trims.mjs — do not hand-edit; re-run after changing a preview
 * WAV or a pack's live level (\`node scripts/gen-preview-trims.mjs --check\` guards staleness).
 * Per-pack preview gain (dB) that level-matches public/snippets/<id>.wav to the live engine at
 * cruise; capped so the trimmed preview peaks ≤ ${PEAK_CEILING_DB} dBFS (master limiter knee).
 */
import { CHRONO_COUPE } from './chronoCoupePack';

export interface PreviewTrimInfo {
  liveCruiseLufs: number;
  previewLufs: number;
  previewPeakDb: number;
  /** live − preview, before the peak cap */
  exactDb: number;
  /** applied gain (dB) */
  trimDb: number;
  clamped: boolean;
}

export const PREVIEW_PEAK_CEILING_DB = ${PEAK_CEILING_DB};

export const PREVIEW_TRIM_INFO: Readonly<Record<string, PreviewTrimInfo>> = {
${rows.map(({ id, ...r }) => `  ${keyOf(id)}: ${JSON.stringify(r).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')},`).join('\n')}
};

export const PREVIEW_TRIMS_DB: Readonly<Record<string, number>> = Object.fromEntries(
  Object.entries(PREVIEW_TRIM_INFO).map(([id, r]) => [id, r.trimDb]),
);
`;

if (process.argv.includes('--check')) {
  const { PREVIEW_TRIMS_DB } = await jiti.import(OUT);
  const stale = rows.filter((r) => Math.abs((PREVIEW_TRIMS_DB[r.id] ?? NaN) - r.trimDb) > 0.05 || Number.isNaN(PREVIEW_TRIMS_DB[r.id] ?? NaN));
  const extra = Object.keys(PREVIEW_TRIMS_DB).filter((k) => !ids.includes(k));
  if (stale.length || extra.length) {
    console.error(`previewTrims.ts stale: ${[...stale.map((r) => r.id), ...extra].join(', ')}`);
    process.exit(1);
  }
  console.log('previewTrims.ts up to date');
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}`);
}
process.exit(0);
